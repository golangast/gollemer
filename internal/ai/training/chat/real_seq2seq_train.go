const (
	realBatchSize = 32
	realMaxEpochs = 200
	realBaseLR    = 1e-3
	realClip      = 1.0
)

// heldProbe is one held-out evaluation case: an input the model never
// trained on, plus its reference answer.
type heldProbe struct {
	in, ref string
}

// domainTrainData is everything RunRealSeq2SeqTraining needs before the
// training loop: augmented training pairs, held-out base pairs, held-out
// probes, the training vocabulary, and the tokenizer.
type domainTrainData struct {
	trainPairs []ChatPair
	heldBase   []ChatPair
	probes     []heldProbe
	v          *vocab.Vocabulary
	tok        *tokenizer.Tokenizer
}

// prepareDomainTrainData loads the chat dataset, selects one domain, runs
// the deterministic 80/20 train/held-out split with synonym augmentation,
// and builds the training vocabulary + tokenizer. Extracted from
// RunRealSeq2SeqTraining so checkpoint-resume can verify a checkpoint's
// vocabulary matches today's data before resuming from it.
// buildCappedVocab builds a frequency-capped vocabulary for the codeintent
// domain: the long tail of rare identifiers explodes the output layer
// (256x17k) and dominates training time, so only the top-N tokens by
// frequency are kept. The ordering is fully deterministic — frequency
// descending, ties broken by token string ascending — because the training
// vocabulary is hashed into the checkpoint fingerprint that -resume uses to
// validate a checkpoint. (An earlier version sorted by frequency alone over
// randomized map iteration order, so every process built a different vocab
// and -resume always refused the checkpoint.)
func buildCappedVocab(trainPairs []ChatPair, cap int) *vocab.Vocabulary {
	v := vocab.NewVocabulary()
	freq := map[string]int{}
	for _, p := range trainPairs {
		for _, t := range tokenizeLower(p.Input) {
			freq[t]++
		}
		for _, t := range tokenizeLower(p.Output) {
			freq[t]++
		}
	}
	type kv struct {
		tok string
		n   int
	}
	sorted := make([]kv, 0, len(freq))
	for t, n := range freq {
		sorted = append(sorted, kv{t, n})
	}
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].n != sorted[j].n {
			return sorted[i].n > sorted[j].n
		}
		return sorted[i].tok < sorted[j].tok
	})
	for i, kv := range sorted {
		if i >= cap {
			break
		}
		v.AddToken(kv.tok)
	}
	return v
}

func prepareDomainTrainData(projectRoot, domain string) (*domainTrainData, error) {
	datasetPath := ChatDatasetPath(projectRoot)
	if domain == RouterDomain {
		// The router trains on (message, domain-label) pairs, not chat
		// pairs; its data lives in a separate file derived from the
		// quality-gated chat dataset.
		datasetPath = RouterDatasetPath(projectRoot)
	} else if domain == CopyExpDomain {
		// The copy experiment trains on grounding-only pairs in its own
		// file, separate from the v3 codeintent run's data.
		datasetPath = CopyExpDatasetPath(projectRoot)
	} else if domain == CodeIntentDomain || domain == CodeIntentBigDomain {
		// The code-intent model trains on distilled (code+question ->
		// answer) triples generated by the analyzer. The big variant uses
		// the same data.
		datasetPath = CodeIntentDatasetPath(projectRoot)
	} else {
		seeded, err := SeedChatDataset(projectRoot)
		if err != nil {
			return nil, err
		}
		log.Printf("[REAL-SEQ2SEQ] dataset: %d pairs (%s)", seeded, datasetPath)
	}
	all, err := LoadChatDataset(datasetPath)
	if err != nil {
		return nil, err
	}
	base := make([]ChatPair, 0, len(all))
	// The big variant trains on the same pairs as codeintent.
	wantDomain := domain
	if domain == CodeIntentBigDomain {
		wantDomain = CodeIntentDomain
	}
	for _, p := range all {
		if p.Domain == wantDomain {
			base = append(base, p)
		}
	}
	log.Printf("[REAL-SEQ2SEQ] domain=%q: %d pairs (of %d total)", domain, len(base), len(all))
	if len(base) < 10 {
		return nil, fmt.Errorf("need at least 10 base pairs in domain %q, have %d", domain, len(base))
	}

	// Deterministic 80/20 split so results are reproducible.
	rng := rand.New(rand.NewSource(20260926))
	order := rng.Perm(len(base))
	nTrain := int(0.8 * float64(len(base)))
	trainBase := make([]ChatPair, 0, nTrain)
	heldBase := make([]ChatPair, 0, len(base)-nTrain)
	for i, idx := range order {
		if i < nTrain {
			trainBase = append(trainBase, base[idx])
		} else {
			heldBase = append(heldBase, base[idx])
		}
	}

	// Augment training inputs with synonym paraphrases (input side only).
	// Collision-aware: a variant is skipped when it normalizes to the same
	// input as a DIFFERENT base pair with a different output — otherwise
	// augmentation teaches near-identical inputs with conflicting labels
	// (e.g. "i'm unhappy" from "I'm sad" vs base "I'm unhappy."), which a
	// tiny model cannot satisfy and which blurs the class boundary.
	// The gocode domain uses code-safe synonyms only: social swaps like
	// hello->hi would blur "hello world program" vs "hello name function".
	syns := socialSynonyms
	if domain == GocodeDomain {
		syns = gocodeSynonyms
	}
	var trainPairs []ChatPair
	if IsCodeIntentFamily(domain) {
		// No synonym augmentation for code: swapping words inside
		// identifiers or literals would corrupt the code-question
		// alignment the model must learn.
		trainPairs = trainBase
	} else {
		trainPairs = augmentInputs(base, trainBase, syns)
	}

	// Held-out probes: paraphrases of held-out inputs the model never sees.
	// (No synonym paraphrases for codeintent: they'd corrupt the code.)
	var probes []heldProbe
	for _, p := range heldBase {
		probes = append(probes, heldProbe{in: p.Input, ref: p.Output})
		if IsCodeIntentFamily(domain) {
			continue
		}
		for _, sv := range synonymVariants(p.Input, 2, syns) {
			probes = append(probes, heldProbe{in: sv, ref: p.Output})
		}
	}
	log.Printf("[REAL-SEQ2SEQ] %d base pairs -> %d train (augmented %d), %d held-out base, %d probes",
		len(base), len(trainBase), len(trainPairs), len(heldBase), len(probes))

	// Vocabulary from TRAINING data only — held-out words stay unknown,
	// which is exactly what the probes test.
	v := vocab.NewVocabulary()
	if IsCodeIntentFamily(domain) {
		// Cap the code vocab by frequency: the long tail of rare
		// identifiers explodes the output layer (256x17k) and dominates
		// training time. Top 8k tokens cover the signal.
		v = buildCappedVocab(trainPairs, 8000)
	} else {
		for _, p := range trainPairs {
			for _, t := range tokenizeLower(p.Input) {
				v.AddToken(t)
			}
			for _, t := range tokenizeLower(p.Output) {
				v.AddToken(t)
			}
		}
	}
	tok, err := tokenizer.NewTokenizer(v)
	if err != nil {
		return nil, err
	}
	log.Printf("[REAL-SEQ2SEQ] vocab size=%d", v.Size())
	return &domainTrainData{trainPairs: trainPairs, heldBase: heldBase, probes: probes, v: v, tok: tok}, nil
}

// ckptMeta is the sidecar written next to every training checkpoint. It
// records exactly where a killed run stopped so -resume can pick up with
// the same learning rate, best-loss tracking, and vocabulary it had.
type ckptMeta struct {
	Epoch              int     `json:"epoch"`                // last completed epoch
	Best               float64 `json:"best"`                 // best train loss so far
	LastCheckpointBest float64 `json:"last_checkpoint_best"` // best loss at last checkpoint write
	LR                 float32 `json:"lr"`                   // learning rate in effect at Epoch
	EpochsNoImprove    int     `json:"epochs_no_improve"`
	VocabFP            uint64  `json:"vocab_fp"` // fingerprint of the training vocabulary
}

// ckptPaths returns the checkpoint weights path and its JSON sidecar. The
// checkpoint lives NEXT TO the production model but under a different name:
// a killed run must never again clobber the good model on disk.
func ckptPaths(projectRoot, domain string) (ckptPath, metaPath string) {
	modelPath := filepath.Join(projectRoot, "data", "models", "gob_models", "real_tiny_seq2seq_"+domain+".gob")
	return modelPath + ".ckpt", modelPath + ".ckpt.json"
}

// latestCkptPaths returns the "latest weights" checkpoint pair. Unlike the
// best-weights checkpoint above, this one is banked every couple of epochs
// regardless of improvement, so a VM kill can never trap a run in a
// deterministic replay of the same non-improving epoch forever (2026-10-09:
// the codeintent run replayed epoch 71 nine times with byte-identical loss
// because the best-only gate never banked it). Resume prefers this file;
// the best-weights file stays the source of truth for final model selection.
func latestCkptPaths(projectRoot, domain string) (latestPath, latestMetaPath string) {
	modelPath := filepath.Join(projectRoot, "data", "models", "gob_models", "real_tiny_seq2seq_"+domain+".gob")
	return modelPath + ".latest", modelPath + ".latest.json"
}

// copyModelParams copies src's parameter values into dst. Both models must
// share the architecture (same domain, same code); mismatched tensors are
// skipped defensively.
func copyModelParams(dst, src *seq2seq.Seq2Seq) {
	dp, sp := dst.Parameters(), src.Parameters()
	for i := range dp {
		if i < len(sp) && len(dp[i].Data) == len(sp[i].Data) {
			copy(dp[i].Data, sp[i].Data)
		}
	}
}

// vocabFingerprint hashes the training vocabulary so resume can refuse a
// checkpoint trained on different data — a vocab index shift would silently
// corrupt the resumed weights.
func vocabFingerprint(v *vocab.Vocabulary) uint64 {
	h := fnv.New64a()
	fmt.Fprintf(h, "size=%d;", v.Size())
	for i := 0; i < v.Size(); i++ {
		fmt.Fprintf(h, "%d=%s;", i, v.GetWord(i))
	}
	return h.Sum64()
}

// saveTrainingCheckpoint writes the best weights and the resume sidecar.
// The production model file is NOT touched — it is only written when
// training completes.
func saveTrainingCheckpoint(model *seq2seq.Seq2Seq, meta ckptMeta, ckptPath, metaPath string) error {
	if err := os.MkdirAll(filepath.Dir(ckptPath), 0o755); err != nil {
		return err
	}
	tmp := ckptPath + ".tmp"
	if err := model.Save(tmp); err != nil {
		return err
	}
	if err := os.Rename(tmp, ckptPath); err != nil {
		return err
	}
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(metaPath+".tmp", data, 0o644); err != nil {
		return err
	}
	return os.Rename(metaPath+".tmp", metaPath)
}

// loadTrainingCheckpoint restores a killed run's best weights for -resume.
// It refuses (returns an error) when the sidecar is missing or the
// vocabulary no longer matches, so a stale checkpoint can never corrupt a
// fresh run — the caller falls back to training from epoch 1.
func loadTrainingCheckpoint(tok *tokenizer.Tokenizer, curFP uint64, ckptPath, metaPath string) (*seq2seq.Seq2Seq, ckptMeta, error) {
	var meta ckptMeta
	data, err := os.ReadFile(metaPath)
	if err != nil {
		return nil, meta, fmt.Errorf("no checkpoint sidecar: %w", err)
	}
	if err := json.Unmarshal(data, &meta); err != nil {
		return nil, meta, fmt.Errorf("bad checkpoint sidecar: %w", err)
	}
	if meta.VocabFP != curFP {
		return nil, meta, fmt.Errorf("checkpoint vocab fingerprint %d != current %d: data changed, refusing resume", meta.VocabFP, curFP)
	}
	model, err := seq2seq.Load(ckptPath, tok)
	if err != nil {
		return nil, meta, fmt.Errorf("loading checkpoint weights: %w", err)
	}
	return model, meta, nil
}

// dimsForDomain returns (embeddingDim, hiddenDim) per domain. The gocode
// domain separates 24 near-identical code templates, so it gets a wider
// model; the gocli domain now separates ~40 near-identical commands, so it
// gets the same wider model. The go domain is the code-understanding
// brain: it learns the analyzer's intent/effect/why mappings, so it gets
// the wider model too. The MoE expert width scales as hiddenDim/2
// automatically. social/makefile keep their original dims so existing .gob
// checkpoints (which store their dims) stay valid and retraining stays
// comparable.
// maxTargetTokens bounds the output length per domain. Chat domains give
// short answers; the codeintent domain explains code and needs room.
func maxTargetTokens(domain string) int {
	if IsCodeIntentFamily(domain) {
		return 200
	}
	return 60
}

func dimsForDomain(domain string) (embedDim, hiddenDim int) {
	if domain == CopyExpDomain {
		// Copy-skill falsification at 128/256: the copy procedure is
		// nearly extractive and should not need 512 hidden units; the
		// smaller model trains ~4x faster per epoch for a quick verdict.
		return 128, 256
	}
	if domain == CodeIntentDomain {
		// 2026-10-12: scaled to 256/512 at John's direction ("try a bigger
		// model anyway") after the masking diagnostic proved the 128/256
		// model never reads the input code (masked mean F1 0.178 > unmasked
		// 0.146; 0/100 file-path echoes; 72/100 outputs citing gollemer-repo
		// paths). Hypothesis under test: the pre-attention bottleneck is a
		// single hidden vector, and at hidden=256 a long code snippet cannot
		// survive compression, so the decoder learns to ignore the code and
		// retrieve memorized answers. A 2x wider bottleneck may let actual
		// code content through. The gate is the masking diagnostic on the
		// trained model, not loss or F1.
		return 256, 512
	}
	if domain == CodeIntentBigDomain {
		// 2026-10-17: John's "Do a and c" — 2x the v3 width to test if
		// capacity is the bottleneck. Same hypothesis as v3, scaled up.
		return 512, 1024
	}
	if domain == GocodeDomain {
		// 2026-10-17: John's "make it bigger" — 256/512 for the harder
		// 1,316-pair training. The 128/256 was for 173 toy pairs.
		return 256, 512
	}
	if domain == GoDomain || domain == GoCliDomain || domain == SocialDomain || domain == MakefileDomain || domain == RouterDomain {
		return 128, 256
	}
	return 64, 128
}

// lrForDomain returns the base learning rate per domain. The 256/512
// codeintent model trains on very long code sequences; at that width the
// 1e-3 base LR tuned for smaller models lets the weights grow until a
// forward pass overflows to NaN (hit at epoch 24 on 2026-10-12: six
// LR-halving rollbacks could not recover because the batch order is fixed
// and the poisonous batch replayed identically). Halve the base LR for the
// big codeintent model only — the other 256/512 domains (gocode/go/gocli)
// train stably at 1e-3.
func lrForDomain(domain string) float32 {
	if domain == CodeIntentDomain || domain == CodeIntentBigDomain {
		return 5e-4
	}
	return realBaseLR
}

// clipForDomain returns the gradient clip norm per domain. Gradient norms
// grow with model width; the big codeintent models get a tighter clip.
func clipForDomain(domain string) float32 {
	if domain == CodeIntentDomain || domain == CodeIntentBigDomain {
		return 0.5
	}
	return realClip
}

// socialSynonyms drives augmentation: swapping a word for a synonym teaches
// the model that meaning survives rephrasing. Single words only; multi-word
// entries are split on spaces when substituted.
var socialSynonyms = map[string][]string{
	"hello": {"hi", "hey", "greetings"}, "hi": {"hello", "hey"}, "hey": {"hi", "hello"},
	"good": {"great", "nice", "fine"}, "great": {"good", "fantastic", "wonderful"},
	"fantastic": {"great", "wonderful"}, "nice": {"good", "lovely"}, "fine": {"good", "okay"},
	"bad": {"terrible", "awful"}, "terrible": {"bad", "awful"},
	"happy": {"glad", "pleased"}, "glad": {"happy", "pleased"}, "sad": {"unhappy", "down"},
	"thanks": {"thank you"}, "thank": {"thanks"},
	"please": {"kindly"}, "yes": {"yeah", "yep"}, "yeah": {"yes", "yep"},
	"no": {"nope", "nah"}, "love": {"adore"}, "like": {"enjoy"},
	"want": {"wish"}, "need": {"require"}, "help": {"assist", "aid"},
	"day": {"morning", "afternoon"}, "morning": {"day"}, "night": {"evening"},
	"today": {"this morning"}, "friend": {"buddy", "pal"},
	"awesome": {"amazing", "great"}, "cool": {"neat", "great"},
	"sorry": {"apologies"}, "welcome": {"greetings"},
	"bye": {"goodbye", "see you"}, "goodbye": {"bye"},
}

// tokenizeLower splits text exactly the way the tokenizer does
// (whitespace + {}[],:\"?!. as single-char tokens), lowercased so the
// model is case-insensitive. It must stay in sync with
// TokenizeAndConvertToIDs in internal/ai/neural/tokenizer.
func tokenizeLower(text string) []string {
	var toks []string
	runes := []rune(strings.ToLower(text))
	i := 0
	for i < len(runes) {
		r := runes[i]
		if r == ' ' || r == '\t' || r == '\n' || r == '\r' {
			i++
			continue
		}
		if strings.ContainsRune(`{}[],:\"?!.`, r) {
			toks = append(toks, string(r))
			i++
			continue
		}
		start := i
		for i < len(runes) && runes[i] != ' ' && runes[i] != '\t' && runes[i] != '\n' && runes[i] != '\r' && !strings.ContainsRune(`{}[],:\"`, runes[i]) {
			i++
		}
		if tok := string(runes[start:i]); tok != "" {
			toks = append(toks, tok)
		}
	}
	return toks
}

// gocodeSynonyms drives augmentation for the gocode domain. Unlike the social
// set, these are verb-level swaps that never change WHICH snippet is wanted:
// "write"/"make"/"create"/"build"/"code" and "give"/"show", "need"/"want" all
// keep the same target function. Social synonyms like hello->hi are BANNED
// here: "write a hello world program" vs "code a hello name function" must
// stay far apart, and swapping hello->hi blurs exactly that boundary.
var gocodeSynonyms = map[string][]string{
	"write":  {"create", "make", "code"},
	"make":   {"create", "build", "write"},
	"create": {"make", "build", "write"},
	"build":  {"make", "create"},
	"code":   {"write", "create"},
	"give":   {"show"},
	"show":   {"give"},
	"need":   {"want"},
	"want":   {"need"},
}

// synonymVariants returns up to n paraphrases of q, each swapping one word
// using the provided synonym map.
func synonymVariants(q string, n int, syns map[string][]string) []string {
	toks := tokenizeLower(q)
	var out []string
	for i, w := range toks {
		for _, syn := range syns[w] {
			nt := append([]string{}, toks...)
			nt[i] = syn
			out = append(out, strings.Join(nt, " "))
			if len(out) >= n {
				return out
			}
		}
	}
	return out
}

// normAugInput canonicalizes an input for collision detection: lowercase,
// punctuation dropped, whitespace collapsed. "I'm unhappy." and "i'm unhappy"
// are the same phrasing and must not carry different labels.
func normAugInput(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '\'' {
			b.WriteRune(r)
		} else if r == ' ' || r == '\t' {
			b.WriteRune(' ')
		}
	}
	return strings.Join(strings.Fields(b.String()), " ")
}

// augmentInputs expands trainBase with synonym variants, skipping any variant
// that collides (after normalization) with a different base pair's input
// carrying a different output.
func augmentInputs(base, trainBase []ChatPair, syns map[string][]string) []ChatPair {
	baseOutputByNorm := make(map[string]string, len(base))
	for _, p := range base {
		n := normAugInput(p.Input)
		if _, dup := baseOutputByNorm[n]; !dup {
			baseOutputByNorm[n] = p.Output
		}
	}
	trainPairs := make([]ChatPair, 0, len(trainBase)*10)
	emitted := make(map[string]string, len(trainPairs))
	for _, p := range trainBase {
		trainPairs = append(trainPairs, p)
		emitted[normAugInput(p.Input)] = p.Output
		for _, v := range synonymVariants(p.Input, 9, syns) {
			n := normAugInput(v)
			if out, collides := baseOutputByNorm[n]; collides && out != p.Output {
				continue // another pair owns this phrasing — don't contradict it
			}
			if out, dup := emitted[n]; dup && out != p.Output {
				continue // an earlier variant already claimed this phrasing
			}
			emitted[n] = p.Output
			trainPairs = append(trainPairs, ChatPair{Input: v, Output: p.Output})
		}
	}
	return trainPairs
}

// encodeInput tokenizes a question for the encoder: [ids...].
// Inputs are normalized the same way as at inference (see
// seq2seq.NormalizeQuery): punctuation variants of one phrasing share one
// encoding, so the model learns the intent once.
func encodeInput(tok *tokenizer.Tokenizer, q string) []int {
	ids, err := tok.Encode(seq2seq.NormalizeQuery(q))
	if err != nil {
		return nil
	}
	return ids
}

// encodeTarget tokenizes an answer for the decoder: [BOS, ids..., EOS].
func encodeTarget(tok *tokenizer.Tokenizer, v *vocab.Vocabulary, a string) []int {
	ids, err := tok.Encode(strings.ToLower(a))
	if err != nil {
		return nil
	}
	out := make([]int, 0, len(ids)+2)
	out = append(out, v.BosID)
	out = append(out, ids...)
	out = append(out, v.EosID)
	return out
}

type encodedPair struct {
	input  []int
	target []int
}

// RunRealSeq2SeqTraining trains the genuine social seq2seq model.
// Only pairs tagged with domain are used — stages stay separate by design.
func RunRealSeq2SeqTraining(projectRoot, domain string, resume bool) error {
	dd, err := prepareDomainTrainData(projectRoot, domain)
	if err != nil {
		return err
	}
	trainPairs, v, tok := dd.trainPairs, dd.v, dd.tok
	probes := dd.probes

	// Encode everything.
	encoded := make([]encodedPair, 0, len(trainPairs))
	maxTgt := maxTargetTokens(domain)
	for _, p := range trainPairs {
		in := encodeInput(tok, p.Input)
		tg := encodeTarget(tok, v, p.Output)
		if len(in) == 0 || len(tg) < 2 || len(tg) > maxTgt {
			continue
		}
		encoded = append(encoded, encodedPair{input: in, target: tg})
	}
	if len(encoded) == 0 {
		return fmt.Errorf("no encodable training pairs")
	}

	// Length-bucketed batches: sort by input length so padding is minimal.
	sort.Slice(encoded, func(i, j int) bool { return len(encoded[i].input) < len(encoded[j].input) })

	curFP := vocabFingerprint(v)
	ckptPath, metaPath := ckptPaths(projectRoot, domain)
	latestCkptPath, latestMetaPath := latestCkptPaths(projectRoot, domain)
	modelPath := filepath.Join(projectRoot, "data", "models", "gob_models", "real_tiny_seq2seq_"+domain+".gob")

	// Training state. A fresh run starts at epoch 1 from random weights;
	// -resume picks up at the checkpoint's next epoch with its learning
	// rate, best loss, and no-improvement counter intact. Adam momentum is
	// NOT restored (fresh momentum on resume) — the divergence-rollback
	// path already treats weight-restore + dropped momentum as safe.
	startEpoch := 1
	lr := lrForDomain(domain)
	best := float32(math.Inf(1))
	epochsNoImprove := 0
	// lastCheckpointBest tracks the best loss at the last checkpoint write.
	// Initialized to MaxFloat32 (not +Inf): the "latest weights" checkpoint
	// is banked on EVERY epoch, and its JSON sidecar cannot represent +Inf —
	// a fresh run with no checkpoints to resume from would crash on epoch 1
	// trying to marshal it (hit 2026-10-11 on the cross-attention retrain).
	lastCheckpointBest := float32(math.MaxFloat32)
	lastCheckpointEpoch := 0 // epoch the checkpoint sidecar was last written at
	var model *seq2seq.Seq2Seq

	resumeFromLatest := false
	var latestModel *seq2seq.Seq2Seq // latest-weights model; copied into the training model after bestParams is snapshotted
	if resume {
		if m, meta, err := loadTrainingCheckpoint(tok, curFP, ckptPath, metaPath); err != nil {
			log.Printf("[REAL-SEQ2SEQ] -resume given but checkpoint unusable (%v); starting fresh from epoch 1", err)
		} else {
			model = m
			startEpoch = meta.Epoch + 1
			lr = meta.LR
			best = float32(meta.Best)
			lastCheckpointBest = float32(meta.LastCheckpointBest)
			lastCheckpointEpoch = meta.Epoch // sidecar Epoch is the epoch of the last checkpoint write
			epochsNoImprove = meta.EpochsNoImprove
			// Prefer the latest-weights checkpoint when it is ahead of the
			// best-weights one: the best-only gate never banks non-improving
			// epochs, and training is deterministic, so without this a kill
			// replays the same epoch with the same loss forever.
			if lm, lmeta, lerr := loadTrainingCheckpoint(tok, curFP, latestCkptPath, latestMetaPath); lerr == nil && lmeta.Epoch > meta.Epoch {
				latestModel = lm
				resumeFromLatest = true
				startEpoch = lmeta.Epoch + 1
				lr = lmeta.LR
				best = float32(lmeta.Best)
				epochsNoImprove = lmeta.EpochsNoImprove
				log.Printf("[REAL-SEQ2SEQ] RESUMED from latest checkpoint: completed epoch=%d best=%.6f lr=%.6f (continuing at epoch %d)",
					lmeta.Epoch, lmeta.Best, lmeta.LR, startEpoch)
			} else {
				log.Printf("[REAL-SEQ2SEQ] RESUMED from checkpoint: completed epoch=%d best=%.6f lr=%.6f (continuing at epoch %d)",
					meta.Epoch, meta.Best, meta.LR, startEpoch)
			}
		}
	}
	if model == nil {
		embedDim, hiddenDim := dimsForDomain(domain)
		// Stage-3 bigger model: the accumulator-binding miss is a long-range
		// dependency limit, and the copy mechanism needs the extra capacity to
		// train stably. The gocli domain separates ~40 near-identical
		// commands and needs the same headroom. The go domain is the
		// code-understanding brain (analyzer-distilled intent/effect/why
		// pairs) and gets the wider model too. Other domains keep their
		// dims so their checkpoints stay valid.
		if domain == GocodeDomain || domain == GoCliDomain || domain == GoDomain {
			embedDim, hiddenDim = 256, 512
		}
		model, err = seq2seq.NewSeq2Seq(v.Size(), v.Size(), embedDim, hiddenDim, tok, v)
		if err != nil {
			return err
		}
		// The copy mechanism is gocode-only: a nil gate means exactly the old
		// behavior, so the other domains are untouched.
		if domain == GocodeDomain {
			model.Decoder.Copy = seq2seq.NewCopyGate(hiddenDim)
		}
		// The encoder-side copy mechanism is codeintent-only: it lets the
		// decoder reproduce input tokens (file paths, signatures) verbatim.
		// The 4-head residual cross-attention is codeintent-only too: the
		// decoder attends to the encoder's per-timestep outputs, so it can
		// actually READ the input code instead of relying solely on the
		// compressed final state. (The 1-head PoC replaced the decoder state
		// and scored worse than baseline; 4 heads with a residual add fix
		// that.) Nil gates mean exactly the old behavior for other domains.
		if IsCodeIntentFamily(domain) {
			crossAttn, err := nn.NewMultiHeadCrossAttention(hiddenDim, hiddenDim, hiddenDim, 4, 4)
			if err != nil {
				return err
			}
			model.Decoder.CrossAttn = crossAttn
			model.Decoder.EncoderCopy = seq2seq.NewCopyGate(hiddenDim)
			// Positional encodings on the copy-attention keys: encoder LSTM
			// states are too similar across positions (mean cosine ~0.70)
			// for dot-product attention to focus sharply. Each position
			// needs a distinctive signature for pointing to work.
			model.Decoder.EncoderCopy.UsePosEnc = true
		}
		// NOTE: no SetExactMap call — the saved model must generate, not retrieve.
	}
	opt := nn.NewOptimizer(model.Parameters(), lrForDomain(domain), clipForDomain(domain))
	adam, ok := opt.(*nn.Adam)
	if !ok {
		return fmt.Errorf("optimizer is not *nn.Adam")
	}
	adam.SetLearningRate(lr)
	// Fresh run: snapshot of the random-init weights with best=+Inf, so the
	// first epoch always sets the baseline. Resume: snapshot of the
	// checkpoint's best weights with its recorded best loss.
	bestParams := adam.SnapshotParameters()
	if resumeFromLatest {
		// The model currently holds the best weights, so the snapshot above
		// is the true best-weights baseline (deep copies). Now load the
		// latest weights into the training model so the run continues forward
		// instead of replaying the best checkpoint's next epoch forever.
		copyModelParams(model, latestModel)
		latestModel = nil // allow GC; the weights now live in the training model
	}
	rollbacks := 0

	padID := v.PaddingTokenID
	batches := makeBatches(encoded, realBatchSize, padID)
	log.Printf("[REAL-SEQ2SEQ] %d encoded pairs, %d batches/epoch, lr=%.6f", len(encoded), len(batches), lr)

	for epoch := startEpoch; epoch <= realMaxEpochs; epoch++ {
		// Step decay every 40 epochs.
		if epoch > 1 && (epoch-1)%40 == 0 {
			lr *= 0.5
			adam.SetLearningRate(lr)
		}
		var epochLoss float64
		validBatches := 0
		nanSkips := 0
		for bi, b := range batches {
			adam.ZeroGrad()
			loss, err := seq2seq.TrainBatch(model, b.inputs, b.targets, padID)
			if err != nil {
				return fmt.Errorf("epoch %d: %w", epoch, err)
			}
			if math.IsNaN(float64(loss)) || math.IsInf(float64(loss), 0) {
				// Poisonous batch: the forward pass overflowed (typically an
				// extreme-length sequence at this model width). Applying the
				// NaN gradients would corrupt every parameter, and the old
				// epoch-level rollback just replayed the same fixed batch
				// order into the same NaN forever (2026-10-12: epochs 24-29,
				// six failed rollbacks). Skip the batch's update instead; its
				// gradients are discarded by the next ZeroGrad and the
				// weights are untouched.
				nanSkips++
				log.Printf("[REAL-SEQ2SEQ] epoch=%d batch=%d/%d loss=NaN/Inf; skipping batch update (%d skips this epoch)",
					epoch, bi, len(batches), nanSkips)
				continue
			}
			epochLoss += float64(loss)
			validBatches++
			adam.ClipGradients()
			adam.Step()
		}
		var avg float32
		if validBatches > 0 {
			avg = float32(epochLoss / float64(validBatches))
		} else {
			avg = float32(math.NaN())
		}

		// Divergence rollback: restore best weights, drop momentum, halve LR.
		if math.IsNaN(float64(avg)) || math.IsInf(float64(avg), 0) || nanSkips > 3 || (epoch > 5 && avg > best*3) {
			rollbacks++
			log.Printf("[REAL-SEQ2SEQ] DIVERGENCE at epoch=%d loss=%.6f (best=%.6f); rolling back (lr %.6f -> %.6f)",
				epoch, avg, best, lr, lr*0.5)
			adam.RestoreParameters(bestParams)
			lr *= 0.5
			adam.SetLearningRate(lr)
			if rollbacks > 5 {
				log.Printf("[REAL-SEQ2SEQ] too many rollbacks; stopping")
				break
			}
			continue
		}

		if avg < best {
			best = avg
			bestParams = adam.SnapshotParameters()
			epochsNoImprove = 0
		} else {
			epochsNoImprove++
		}
		// Best is chosen on TRAIN loss so the held-out probes stay untouched.
		log.Printf("[REAL-SEQ2SEQ] epoch=%d avg_loss=%.6f best=%.6f lr=%.6f", epoch, avg, best, lr)
		if epoch%10 == 0 {
			if model.Decoder.MoE != nil {
				log.Printf("[REAL-SEQ2SEQ] MoE expert usage: %.2f %.2f %.2f %.2f",
					model.Decoder.MoE.ExpertUsage()[0], model.Decoder.MoE.ExpertUsage()[1],
					model.Decoder.MoE.ExpertUsage()[2], model.Decoder.MoE.ExpertUsage()[3])
			}
		}
		// Checkpoint the best model often: VM restarts keep killing runs
		// (2026-10-08: ~7 kills in one day on the codeintent run), so bank
		// progress on ANY improvement instead of only even epochs — the old
		// even-epoch gate silently discarded improvements made on odd
		// epochs. The 2-epoch spacing is kept as a minimum interval so a
		// fast-falling loss early on doesn't spam 20MB checkpoint writes.
		// The checkpoint goes to SIDE files — the production model is only
		// written when training completes, so a kill can never again leave
		// a half-trained model in its place.
		if best < lastCheckpointBest && epoch-lastCheckpointEpoch >= 2 {
			// Best-checkpoint: a killed run keeps its progress and -resume
			// picks it up.
			adam.RestoreParameters(bestParams)
			meta := ckptMeta{
				Epoch:              epoch,
				Best:               float64(best),
				LastCheckpointBest: float64(best),
				LR:                 lr,
				EpochsNoImprove:    epochsNoImprove,
				VocabFP:            curFP,
			}
			if err := saveTrainingCheckpoint(model, meta, ckptPath, metaPath); err != nil {
				return err
			}
			lastCheckpointBest = best
			lastCheckpointEpoch = epoch
			log.Printf("[REAL-SEQ2SEQ] checkpointed best model (loss=%.6f) to %s", best, ckptPath)
		}
		// Bank the latest weights on EVERY completed epoch, regardless of
		// improvement. Training is deterministic, so without this a VM kill
		// landing after a non-improving epoch replays that exact epoch (same
		// loss) forever — the codeintent run replayed epoch 71 nine times on
		// 2026-10-09. The first version of this gate banked only even epochs
		// (epoch%2 == 0), which left the same trap for odd epochs: a kill
		// after epoch 73 with the latest banked at 72 resumed from the
		// epoch-72 best checkpoint and replayed 73 three times (2026-10-09
		// 17:15-18:43, all loss 0.104982, zero net progress). One ~20MB write
		// per ~13-minute epoch is cheap; resume continuity is worth it.
		// Resume prefers this file; the best-weights file above stays the
		// source of truth for final model selection.
		{
			lmeta := ckptMeta{
				Epoch:              epoch,
				Best:               float64(best),
				LastCheckpointBest: float64(lastCheckpointBest),
				LR:                 lr,
				EpochsNoImprove:    epochsNoImprove,
				VocabFP:            curFP,
			}
			if err := saveTrainingCheckpoint(model, lmeta, latestCkptPath, latestMetaPath); err != nil {
				return err
			}
			// Keep the best-weights file in step at the same cadence: if the
			// running best improved since the last best-bank (e.g. on an odd
			// epoch the 2-epoch spacing rule skipped), bank it now so a later
			// resume's bestParams baseline always matches the recorded best.
			if best < lastCheckpointBest {
				adam.RestoreParameters(bestParams)
				bmeta := ckptMeta{
					Epoch:              epoch,
					Best:               float64(best),
					LastCheckpointBest: float64(best),
					LR:                 lr,
					EpochsNoImprove:    epochsNoImprove,
					VocabFP:            curFP,
				}
				if err := saveTrainingCheckpoint(model, bmeta, ckptPath, metaPath); err != nil {
					return err
				}
				lastCheckpointBest = best
				lastCheckpointEpoch = epoch
				log.Printf("[REAL-SEQ2SEQ] checkpointed best model (loss=%.6f) to %s", best, ckptPath)
			}
		}
		if epochsNoImprove >= 30 {
			log.Printf("[REAL-SEQ2SEQ] early stopping: 30 epochs without improvement")
			break
		}
	}

	// Restore the best weights seen, then save — no ExactMap, ever.
	adam.RestoreParameters(bestParams)
	if err := os.MkdirAll(filepath.Dir(modelPath), 0o755); err != nil {
		return err
	}
	if err := model.Save(modelPath); err != nil {
		return err
	}
	log.Printf("[REAL-SEQ2SEQ] saved best model (loss=%.6f) to %s", best, modelPath)

	// Run completed: the checkpoint has served its purpose. Remove it so a
	// later -resume starts fresh instead of picking up a stale checkpoint.
	if err := os.Remove(ckptPath); err != nil && !os.IsNotExist(err) {
		log.Printf("[REAL-SEQ2SEQ] warning: could not remove %s: %v", ckptPath, err)
	}
	if err := os.Remove(metaPath); err != nil && !os.IsNotExist(err) {
		log.Printf("[REAL-SEQ2SEQ] warning: could not remove %s: %v", metaPath, err)
	}
	if err := os.Remove(latestCkptPath); err != nil && !os.IsNotExist(err) {
		log.Printf("[REAL-SEQ2SEQ] warning: could not remove %s: %v", latestCkptPath, err)
	}
	if err := os.Remove(latestMetaPath); err != nil && !os.IsNotExist(err) {
		log.Printf("[REAL-SEQ2SEQ] warning: could not remove %s: %v", latestMetaPath, err)
	}

	// Held-out probe: every generation printed verbatim, good or bad.
	log.Printf("[REAL-SEQ2SEQ] held-out probe: %d paraphrased questions the model never saw", len(probes))
	goCase := map[string]string{}
	if domain == GocodeDomain {
		goCase = goIdentCaseMap(projectRoot)
	}
	for i, pr := range probes {
		out, err := model.Predict(strings.ToLower(pr.in), 40)
		if err != nil {
			log.Printf("[REAL-SEQ2SEQ] probe %d error: %v", i, err)
			continue
		}
		shown := tidyDecode(out)
		if domain == GocodeDomain {
			shown = tidyGoCode(out, goCase)
		}
		log.Printf("[REAL-SEQ2SEQ] Q: %s\n[REAL-SEQ2SEQ] A: %s", pr.in, shown)
	}
	return nil
}

type batch struct {
	inputs  [][]int
	targets [][]int
}

// makeBatches pads each bucket to its own max lengths.
func makeBatches(enc []encodedPair, size, padID int) []batch {
	var out []batch
	for i := 0; i < len(enc); i += size {
		end := i + size
		if end > len(enc) {
			end = len(enc)
		}
		grp := enc[i:end]
		maxIn, maxTg := 0, 0
		for _, p := range grp {
			if len(p.input) > maxIn {
				maxIn = len(p.input)
			}
			if len(p.target) > maxTg {
				maxTg = len(p.target)
			}
		}
		b := batch{}
		for _, p := range grp {
			in := make([]int, maxIn)
			copy(in, p.input)
			for k := len(p.input); k < maxIn; k++ {
				in[k] = padID
			}
			tg := make([]int, maxTg)
			copy(tg, p.target)
			for k := len(p.target); k < maxTg; k++ {
				tg[k] = padID
			}
			b.inputs = append(b.inputs, in)
			b.targets = append(b.targets, tg)
		}
		out = append(out, b)
	}
	return out
}

// tidyDecode fixes the spacing the word-join decoder leaves around punctuation.
func tidyDecode(s string) string {
	for _, p := range []string{"?", "!", ".", ",", ":", ";", "'"} {
		s = strings.ReplaceAll(s, " "+p, p)
	}
	s = strings.ReplaceAll(s, "  ", " ")
	return strings.TrimSpace(s)
}

// RunReclassifyDomains re-tags the whole dataset with the current classifier.
func RunReclassifyDomains(projectRoot string) error {
	counts, err := ReclassifyDomains(projectRoot)
	if err != nil {
		return err
	}
	log.Printf("[DATA] reclassified: %v", counts)
	return nil
}

// RunImportChatPairs imports new training pairs through the quality gate.
func RunImportChatPairs(projectRoot, importPath string) error {
	admitted, quarantined, err := ImportChatPairs(projectRoot, importPath)
	if err != nil {
		return err
	}
	log.Printf("[DATA] admitted %d new pairs", admitted)
	for _, q := range quarantined {
		log.Printf("[DATA] quarantined %s", q)
	}
	if admitted == 0 && len(quarantined) == 0 {
		log.Printf("[DATA] nothing to import")
	}
	return nil
}
